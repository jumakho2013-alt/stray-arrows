// Compose a number string into one mask. ≤3 digits: single row with 2-col
// gutters. 4 digits: 2×2 stack (better aspect for the portrait board).
function composeNumber(numStr) {
  const s = String(numStr);
  if (!/^[0-9]+$/.test(s)) throw new Error('composeNumber: not a number: ' + s);
  const rowOf = (digits) => {
    const parts = digits.map((d) => DIGITS[d]);
    const H = 11;
    const out = [];
    for (let r = 0; r < H; r++) {
      out.push(parts.map((p) => p[r]).join('..'));
    }
    return out;
  };
  if (s.length <= 3) return rowOf(s.split(''));
  if (s.length === 4) {
    const top = rowOf(s.slice(0, 2).split(''));
    const bot = rowOf(s.slice(2).split(''));
    const W = Math.max(top[0].length, bot[0].length);
    const pad = (rows) => rows.map((r) => r.padEnd(W, '.'));
    return [...pad(top), '.'.repeat(W), '.'.repeat(W), ...pad(bot)];
  }
  throw new Error('composeNumber: unsupported length ' + s.length);
}

// ── Helpers ──────────────────────────────────────────────────────────

function maskCells(rows) {
  const cells = [];
  for (let r = 0; r < rows.length; r++)
    for (let c = 0; c < rows[r].length; c++)
      if (rows[r][c] === '#') cells.push([r, c]);
  return cells;
}

function inMask(rows, r, c) {
  return r >= 0 && r < rows.length && c >= 0 && c < (rows[r] || '').length && rows[r][c] === '#';
}

const N4 = [[0, 1], [0, -1], [1, 0], [-1, 0]];

function components(rows) {
  const seen = new Set();
  const comps = [];
  for (const [r0, c0] of maskCells(rows)) {
    const k0 = r0 + ',' + c0;
    if (seen.has(k0)) continue;
    const q = [[r0, c0]];
    seen.add(k0);
    let size = 0;
    while (q.length) {
      const [r, c] = q.pop();
      size++;
      for (const [dr, dc] of N4) {
        const nr = r + dr, nc = c + dc, k = nr + ',' + nc;
        if (inMask(rows, nr, nc) && !seen.has(k)) { seen.add(k); q.push([nr, nc]); }
      }
    }
    comps.push(size);
  }
  return comps;
}

function validateMask(name, rows, opts = {}) {
  const errors = [];
  const warnings = [];
  const cells = maskCells(rows);
  const n = cells.length;
  const W = Math.max(...rows.map((r) => r.length));
  const H = rows.length;
  for (const row of rows) {
    if (/[^#.]/.test(row)) errors.push('bad char in row: ' + JSON.stringify(row));
  }
  const comps = components(rows);
  if (!opts.multiComponent && comps.length !== 1) {
    errors.push(`must be 1 connected component, got ${comps.length} (sizes ${comps.join(',')})`);
  }
  if (opts.multiComponent && comps.some((s) => s < 4)) {
    errors.push('a component is smaller than 4 cells: ' + comps.join(','));
  }
  let low = 0;
  for (const [r, c] of cells) {
    let nb = 0;
    for (const [dr, dc] of N4) if (inMask(rows, r + dr, c + dc)) nb++;
    if (nb < 2) low++;
  }
  const lowPct = n ? low / n : 1;
  if (lowPct > 0.15) errors.push(`${(lowPct * 100).toFixed(0)}% of cells have <2 neighbours (max 15%)`);
  if (!opts.anyCellCount) {
    if (n < 60 || n > 170) errors.push(`cell count ${n} outside 60–170`);
    else if (n < 70 || n > 140) warnings.push(`cell count ${n} outside target 70–140`);
  }
  return { name, ok: errors.length === 0, errors, warnings, cells: n, w: W, h: H, lowNeighborPct: lowPct };
}

// Nearest-neighbour upscale to `scale` (≥1, rational ok). Preserves
// connectivity for NN with scale ≥ 1.
function rasterize(rows, scale) {
  if (scale === 1) return rows.slice();
  const H = rows.length, W = Math.max(...rows.map((r) => r.length));
  const oh = Math.round(H * scale), ow = Math.round(W * scale);
  const out = [];
  for (let r = 0; r < oh; r++) {
    let line = '';
    const sr = Math.min(H - 1, Math.floor((r + 0.5) / scale));
    for (let c = 0; c < ow; c++) {
      const sc = Math.min(W - 1, Math.floor((c + 0.5) / scale));
      line += (rows[sr][sc] === '#') ? '#' : '.';
    }
    out.push(line);
  }
  return out;
}

// Board = mask bbox + 1-cell margin all sides. Returns {cols, rows, cells}
// where cells are board coordinates of mask cells.
function toBoard(rows) {
  const cells = maskCells(rows);
  const minR = Math.min(...cells.map((c) => c[0]));
  const maxR = Math.max(...cells.map((c) => c[0]));
  const minC = Math.min(...cells.map((c) => c[1]));
  const maxC = Math.max(...cells.map((c) => c[1]));
  const M = 1; // margin
  return {
    rows: maxR - minR + 1 + 2 * M,
    cols: maxC - minC + 1 + 2 * M,
    cells: cells.map(([r, c]) => [r - minR + M, c - minC + M]),
  };
}

const SHAPE_NAMES = Object.keys(MASKS);

// Masks that intentionally have several components (like a paw's toes).
// Each component still packs independently; min component size 4.
const MULTI_OK = new Set(['paw']);

module.exports = { MASKS, DIGITS, SHAPE_NAMES, MULTI_OK, composeNumber, maskCells, validateMask, rasterize, toBoard, inMask, components };

// ── CLI ──────────────────────────────────────────────────────────────
if (require.main === module) {
  const arg = process.argv[2];
  const dump = (name, rows, opts) => {
    const v = validateMask(name, rows, opts);
    console.log('\n── ' + name + ` (${v.w}×${v.h}, ${v.cells} cells, <2nb ${(v.lowNeighborPct * 100).toFixed(0)}%)`);
    console.log(rows.join('\n'));
    for (const e of v.errors) console.log('  ✗ ' + e);
    for (const w of v.warnings) console.log('  ⚠ ' + w);
    return v.ok;
  };
  if (arg && /^[0-9]+$/.test(arg)) {
    dump(arg, composeNumber(arg), { multiComponent: true, anyCellCount: true });
  } else if (arg) {
    if (!MASKS[arg]) { console.error('unknown mask: ' + arg); process.exit(1); }
    process.exit(dump(arg, MASKS[arg]) ? 0 : 1);
  } else {
    let fails = 0;
    for (const name of SHAPE_NAMES) {
      const v = validateMask(name, MASKS[name], { multiComponent: MULTI_OK.has(name) });
      const flag = v.ok ? (v.warnings.length ? '⚠' : '✓') : '✗';
      console.log(`${flag} ${name.padEnd(10)} ${String(v.cells).padStart(3)} cells  ${v.w}×${v.h}  <2nb ${(v.lowNeighborPct * 100).toFixed(0)}%  ${v.errors.join('; ')}${v.warnings.join('; ')}`);
      if (!v.ok) fails++;
    }
    // numbers
    for (const num of ['50', '100', '500', '1000', '2200']) {
      const v = validateMask(num, composeNumber(num), { multiComponent: true, anyCellCount: true });
      const flag = v.ok ? '✓' : '✗';
      console.log(`${flag} #${num.padEnd(9)} ${String(v.cells).padStart(3)} cells  ${v.w}×${v.h}  ${v.errors.join('; ')}`);
      if (!v.ok) fails++;
    }
    console.log(fails ? `\n${fails} mask(s) FAILED` : `\nAll ${SHAPE_NAMES.length} masks + digits OK`);
    process.exit(fails ? 1 : 0);
  }
}
