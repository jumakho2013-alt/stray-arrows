#!/usr/bin/env node
// Shape mask library for the shape-level generator (tools/gen-shape-levels.js).
//
// Each mask is ASCII art: '#' = playable cell, '.' = empty. Masks are drawn
// at a 12-22 column "design resolution" and upscaled by rasterize() to the
// tier's target grid. The generator packs 100% of mask cells with snake
// arrows so the silhouette reads as a woven picture on the board.
//
// Design rules (enforced by validateMask):
//   • pictorial masks are ONE 4-connected component
//   • ≥85% of cells have ≥2 orthogonal neighbours inside the mask
//     (limits 1-wide appendages that force degenerate 2-cell arrows)
//   • 60–170 cells at design resolution (target 70–140)
//
// Digits are a chunky 7×11 font with 2-cell strokes, composed side by side
// (with a 2-col gutter) for milestone numbers — "50", "100" … "2200".
// Multi-digit masks are several connected components; that's legal (the
// game validates arrows, not board connectivity).
//
// CLI:
//   node tools/shape-masks.js            # validate all masks, print stats
//   node tools/shape-masks.js heart      # dump one mask + stats
//   node tools/shape-masks.js 1200       # dump a composed number mask

